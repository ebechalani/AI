export type IconName = keyof typeof ICONS;

/** Every name NamedIcon can draw, for seed and migration data to choose from. */
export const ICON_NAMES = Object.keys(ICONS) as IconName[];

const FALLBACK_ICON = Shapes;

// 'brain-circuit' and 'brainCircuit' are read as 'BrainCircuit'.
function toComponentName(name: string): string {
  return name
    .split(/[-_\s]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
}

function isIconName(name: string): name is IconName {
  return Object.hasOwn(ICONS, name);
}

export interface NamedIconProps extends Omit<LucideProps, 'ref' | 'name'> {
  /** A lucide-react component name (`BookOpen`); the kebab-case form is accepted too. */
  name: string;
}

/** Decorative by default (`aria-hidden`); the text next to it carries the meaning. */
export function NamedIcon({ name, ...props }: NamedIconProps) {
  const componentName = toComponentName(name);
  const Icon = isIconName(componentName) ? ICONS[componentName] : FALLBACK_ICON;
  return <Icon aria-hidden="true" {...props} />;
}
